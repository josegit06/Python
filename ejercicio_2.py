print ("vamos a calcular el perimetro y el area de un rectangulo")

base = float(input("Introduce la base del rectangulo: "))
altura = float(input("Introduce la altura del rectangulo: "))

perimetro = 2 * (base + altura)
area = base * altura

print (f'Teniendo en cuenta que la base del rectangulo es {base} y su altura es {altura}, su perímetro es {perimetro} y su area es {area}')
